// Import the Next.js components and CSS modules used by every page layout.
import Head from 'next/head';
import Image from 'next/image';
import styles from './layout.module.css';
import utilStyles from '../styles/utils.module.css';
import Link from 'next/link';
 
// Shared identity and metadata used throughout the site.
const name = 'Renee';
export const siteTitle = 'Next.js Sample Website';
 
// Provide common page structure, metadata, navigation, and profile branding.
export default function Layout({ children, home }) {
  return (
    <div className={styles.container}>
      {/* Define metadata shared by pages that use this layout. */}
      <Head>
        <link rel="icon" href="/favicon.ico" />
        <meta
          name="description"
          content="Learn how to build a personal website using Next.js"
        />
        <meta
          property="og:image"
          content={`https://og-image.vercel.app/${encodeURI(
            siteTitle,
          )}.png?theme=light&md=0&fontSize=75px&images=${encodeURIComponent(
            'https://nextjs.org/static/nextjs-logo.svg',
          )}`}
        />
        <meta name="og:title" content={siteTitle} />
        <meta name="twitter:card" content="summary_large_image" />
      </Head>
      <header className={styles.header}>
        {/* Home pages use a large profile image; other pages use a linked thumbnail. */}
        {home ? (
          <>
            <Image
              priority
              src="/images/profile.jpg"
              className={utilStyles.borderCircle}
              height={144}
              width={144}
              alt=""
            />
            <h1 className={utilStyles.heading2Xl}>{name}</h1>
          </>
        ) : (
          <>
            <Link href="/">
              <Image
                priority
                src="/images/profile.jpg"
                className={utilStyles.borderCircle}
                height={108}
                width={108}
                alt=""
              />
            </Link>
            <h2 className={utilStyles.headingLg}>
              <Link href="/" className={utilStyles.colorInherit}>
                {name}
              </Link>
            </h2>
          </>
        )}
      </header>
      {/* Render the page-specific content inside the shared layout. */}
      <main>{children}</main>
      {/* Detail pages get an additional navigation link below their content. */}
      {!home && (
        <div className={styles.backToHome}>
          <Link href="/">← Back to home</Link>
        </div>
      )}
    </div>
  );
}